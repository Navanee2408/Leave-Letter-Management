import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  MAX_SUPPORTING_DOCUMENT_BYTES,
  SUPPORTED_DOCUMENT_TYPES,
} from '../constants/index.js'
import { AppError } from '../utils/AppError.js'

const DEFAULT_STORAGE_DIR = fileURLToPath(
  new URL('../../storage/leave-documents/', import.meta.url),
)

const PDF_SIGNATURE = Buffer.from('%PDF-')
const JPEG_SIGNATURE = Buffer.from([0xff, 0xd8, 0xff])
const PNG_SIGNATURE = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
])

/**
 * Storage location for private supporting documents. Tests may override it
 * with LEAVE_DOCUMENT_DIR. It is deliberately outside the static/public tree.
 */
export function getLeaveDocumentDir() {
  return process.env.LEAVE_DOCUMENT_DIR
    ? path.resolve(process.env.LEAVE_DOCUMENT_DIR)
    : DEFAULT_STORAGE_DIR
}

function detectDocumentType(buffer) {
  if (buffer.subarray(0, PDF_SIGNATURE.length).equals(PDF_SIGNATURE)) {
    return { mimeType: SUPPORTED_DOCUMENT_TYPES.PDF, extension: 'pdf' }
  }

  if (buffer.subarray(0, JPEG_SIGNATURE.length).equals(JPEG_SIGNATURE)) {
    return { mimeType: SUPPORTED_DOCUMENT_TYPES.JPEG, extension: 'jpg' }
  }

  if (buffer.subarray(0, PNG_SIGNATURE.length).equals(PNG_SIGNATURE)) {
    return { mimeType: SUPPORTED_DOCUMENT_TYPES.PNG, extension: 'png' }
  }

  return null
}

/**
 * Do not trust the uploaded filename. Strip path components and control
 * characters, then keep only a bounded display name. The stored filename is
 * completely separate and generated by the server.
 */
export function sanitizeOriginalName(originalName) {
  const base = path.basename(String(originalName ?? ''))
  const cleaned = base
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/[^\w.\- ()]/g, '_')
    .trim()
    .slice(0, 255)

  return cleaned || 'supporting-document'
}

export async function storeLeaveDocument(file) {
  if (!file?.buffer) return null

  if (file.buffer.length === 0) {
    throw new AppError('Supporting document must not be empty', 400)
  }

  if (file.buffer.length > MAX_SUPPORTING_DOCUMENT_BYTES) {
    throw new AppError('Supporting document must be 5 MB or smaller', 400)
  }

  // Content signature validation means a spoofed extension or MIME type is
  // rejected, and the stored extension is derived from the real bytes.
  const detected = detectDocumentType(file.buffer)

  if (!detected) {
    throw new AppError(
      'Supporting document must be a PDF, JPG, JPEG, or PNG file',
      400,
    )
  }

  const directory = getLeaveDocumentDir()
  await fs.mkdir(directory, { recursive: true, mode: 0o700 })

  const storedName = `${Date.now()}-${crypto.randomUUID()}.${detected.extension}`
  const target = path.join(directory, storedName)

  await fs.writeFile(target, file.buffer, { flag: 'wx', mode: 0o600 })

  return {
    fileName: sanitizeOriginalName(file.originalname),
    storedName,
    mimeType: detected.mimeType,
    size: file.buffer.length,
    uploadedAt: new Date(),
  }
}

export async function removeLeaveDocument(storedName) {
  if (!storedName) return

  try {
    await fs.unlink(path.join(getLeaveDocumentDir(), path.basename(storedName)))
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
}

export async function resolveLeaveDocumentPath(storedName) {
  if (!storedName) {
    throw new AppError('Supporting document not found', 404)
  }

  const directory = getLeaveDocumentDir()
  const safeName = path.basename(storedName)
  const target = path.resolve(directory, safeName)

  if (!target.startsWith(`${path.resolve(directory)}${path.sep}`)) {
    throw new AppError('Supporting document not found', 404)
  }

  try {
    await fs.access(target)
  } catch {
    throw new AppError('Supporting document not found', 404)
  }

  return target
}
